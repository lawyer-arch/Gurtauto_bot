from database.repository.lead_repo import LeadRepository


class LeadService:
    """
    Сервис-прослойка (Service Layer) между handler'ом и репозиторием.

    Текущая реализация — чистый делегат к LeadRepository.create().
    Это осознанный минимализм, продиктованный следующими ограничениями:

    1. Вся бизнес-логика (валидация, обогащение) на данном этапе отсутствует,
       поэтому любое усложнение было бы преждевременной абстракцией.
    2. Управление сессией вынесено в handler (lead_form.py), сервис не владеет
       транзакцией — только repo, полученный через DI.
    3. Уведомление (NotifyService) вызывается в handler'е отдельно после
       create_lead, значит отправка уведомления — не ответственность сервиса.
    4. Модель Lead (database/models/lead.py) плоская, без вычисляемых полей и
       связей — обогащать данные нечем.
    5. Handler уже выполняет минимальную валидацию (телефон, ссылка, фото)
       до вызова сервиса.

    Слой существует как точка расширения: при появлении реальной бизнес-логики
    (проверка дубликатов, обогащение, атомарные операции) она добавится сюда
    без изменения handler'а или репозитория.
    """

    def __init__(self, repo: LeadRepository):
        self.repo = repo

    async def create_lead(self, data):
        return await self.repo.create(data)